/**
 * Tarayıcının varsayılan sistem/arayüz dilini algılar.
 * Desteklenen 7 dilden biriyse onu döner, değilse evrensel "en" (English) döner.
 */
export function detectBrowserLanguage(): Language {
  try {
    const raw = (
      (typeof chrome !== "undefined" && chrome.i18n && chrome.i18n.getUILanguage && chrome.i18n.getUILanguage()) ||
      (typeof navigator !== "undefined" && (navigator.language || (navigator.languages && navigator.languages[0]))) ||
      "en"
    ).toLowerCase();

    // Örn: "tr-TR" -> "tr", "de-DE" -> "de", "en-US" -> "en"
    const prefix = raw.split("-")[0] as Language;

    const supported: Language[] = ["tr", "en", "de", "es", "fr", "ru", "ar"];
    if (supported.includes(prefix)) {
      return prefix;
    }
  } catch {
    // Tarayıcı ortamı dışındaysa fallback
  }
  return "en";
}

